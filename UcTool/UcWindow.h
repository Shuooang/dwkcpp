class CEditCtrlCV : public CEdit
{
public:
	virtual BOOL PreTranslateMessage(MSG* pMsg)
		//BOOL CEditCtrlCV::PreTranslateMessage(MSG* pMsg)
	{
		switch (pMsg->message)
		{
		case WM_KEYDOWN:
		{
			short ctrl = ::GetKeyState(VK_CONTROL);
			if (ctrl < 0)
			{
				switch (pMsg->wParam)
				{
				case 'Z':this->Undo();
					return TRUE;
				case 'X':this->Cut();
					return TRUE;
				case 'C':
				{
					int sc = -1, ec = -1;
					this->GetSel(sc, ec);
					if (sc == -1 && ec == -1)
						this->SetSel(0, -1);
					this->Copy();
					return TRUE;
				}
				case 'V':this->Paste();
					return TRUE;
				case 'A':this->SetSel(0, -1);
					return TRUE;
				}
			}
		}
		}
		return __super::PreTranslateMessage(pMsg);
	}
};


