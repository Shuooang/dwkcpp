#define DDX_IPAddressStr(pDX, IDC, str) {\
	DWORD dwIP{ 0 };\
	if (pDX->m_bSaveAndValidate) {\
		DDX_IPAddress(pDX, IDC, dwIP);\
		str.Format(L"%u.%u.%u.%u", (dwIP >> 24) & 0xFF, (dwIP >> 16) & 0xFF, (dwIP >> 8) & 0xFF, dwIP & 0xFF);\
	} else {\
		DWORD b1{ 0 }, b2{ 0 }, b3{ 0 }, b4{ 0 };\
		swscanf_s(str.GetBuffer(128), L"%u.%u.%u.%u", &b1, &b2, &b3, &b4); str.ReleaseBuffer();\
		dwIP = (b1 & 0xFF) << 24 | (b2 & 0xFF) << 16 | (b3 & 0xFF) << 8 | (b4 & 0xFF);\
		DDX_IPAddress(pDX, IDC, dwIP);\
	}\
